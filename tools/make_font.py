#!/usr/bin/env python3
"""Make an inkerface font from a TrueType/OpenType file (Pillow needed).

The glyphs are rasterized by FreeInk's own generator (gen_font.py, from the
SDK cache), so they match FreeInk's built-in fonts exactly; this tool only
repackages them. Three outputs:

  --format ikf      a font file to put on storage and load at run time:
                    display::load_font(face, disks, volume, "fonts/x.ikf")
  --format header   a C++ header holding the same bytes, to compile a font
                    into a program: display::load_font(face, x_font)
  --format builtin  a platform-layer header with FreeInk types, used only for
                    inkerface's own built-in fonts (lib/inkerface/src/freeink)

Examples:
  python3 tools/make_font.py --ttf NotoSerif-Regular.ttf --size 20 \\
      --format ikf --out serif20.ikf
  python3 tools/make_font.py --ttf NotoSerif-Regular.ttf --size 20 \\
      --format header --name serif_20 --out src/assets/serif_20_font.h

Font format "IKF1" (little-endian), validated by the loader:
  0   4  magic "IKF1"
  4   2  first codepoint          6   2  last codepoint
  8   1  line height              9   1  ascent (baseline below line top)
  10  1  widest glyph             11  1  tallest glyph
  12  1  bits per pixel (1 or 4)  13  1  reserved, 0
  14  2  bitmap size in bytes
  16  7 x (last - first + 1)  glyphs: bitmap offset (2), width, height,
                              advance (1 each), x offset, y offset (signed)
  ..  bitmap bytes (row-major, MSB-first, rows not padded)

MIT License (see LICENSE). Copyright (C) 2026 Tomaz Stih.
"""

import argparse
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parents[1]
gen_font = root / "packages/freeink-sdk/libs/ui/FreeInkUI/tools/gen_font.py"

# Keep fonts "extremely reduced": at most 256 characters, 8-bit metrics.
max_glyphs = 256


def rasterize(ttf, size, first, last, alpha=False):
    """Run FreeInk's generator and read back bitmap, glyphs and metrics."""
    if not gen_font.is_file():
        sys.exit(f"error: {gen_font} not found; run `make sdk` first")
    with tempfile.TemporaryDirectory() as temporary:
        header = Path(temporary) / "font.h"
        subprocess.run([sys.executable, "-I", str(gen_font), "--ttf", str(ttf),
                        "--size", str(size), "--first", hex(first),
                        "--last", hex(last), "--name", "Font",
                        "--out", str(header)] + (["--alpha"] if alpha else []),
                       check=True, stdout=subprocess.DEVNULL)
        text = header.read_text()
    bitmap = bytes(int(v, 16) for v in re.findall(
        r"0x([0-9A-Fa-f]{2})", text.split("kFontBitmap[] = {")[1].split("};")[0]))
    glyphs = [tuple(int(v) for v in row) for row in re.findall(
        r"\{(-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+), (-?\d+)\}",
        text.split("kFontGlyphs[] = {")[1].split("};")[0])]
    metrics = re.search(r"kFontGlyphs, 0x([0-9A-F]+), 0x([0-9A-F]+), "
                        r"(\d+), (\d+), (\d+), (\d+), (\d+)\}", text)
    line_height, ascent, widest, tallest, bpp = (int(metrics[i]) for i in range(3, 8))
    if len(glyphs) != last - first + 1:
        sys.exit("error: unexpected generator output")
    return bitmap, glyphs, (line_height, ascent, widest, tallest, bpp)


def pack(first, last, bitmap, glyphs, metrics):
    """Serialize to the IKF1 format."""
    line_height, ascent, widest, tallest, bpp = metrics
    if max(line_height, ascent, widest, tallest) > 255 or len(bitmap) > 0xFFFF:
        sys.exit("error: font too large; use a smaller --size or range")
    data = bytearray(b"IKF1")
    data += struct.pack("<HHBBBBBBH", first, last, line_height, ascent,
                        widest, tallest, bpp, 0, len(bitmap))
    for offset, width, height, advance, x_offset, y_offset in glyphs:
        data += struct.pack("<HBBBbb", offset, width, height, advance,
                            x_offset, y_offset)
    return bytes(data + bitmap)


def byte_lines(data):
    return ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ","
            for i in range(0, len(data), 12)]


def header_text(name, data, source):
    lines = [
        f"// Font {name}, generated by tools/make_font.py from {source}.",
        "// Load it with display::load_font(face, " + f"{name}_font).",
        "// Check that the source font's license permits embedding bitmaps.",
        "//",
        "// MIT License (see: LICENSE)",
        "// Copyright (C) 2026 Tomaz Stih",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        f"inline constexpr std::array<std::uint8_t, {len(data)}> {name}_font{{",
        *byte_lines(data),
        "};",
    ]
    return "\n".join(lines) + "\n"


def builtin_text(name, first, last, bitmap, glyphs, metrics, source):
    line_height, ascent, widest, tallest, bpp = metrics
    rows = [f"    {{{', '.join(str(v) for v in g)}}}," for g in glyphs]
    lines = [
        f"// Built-in font {name}, generated by tools/make_font.py from",
        f"// {source}.",
        "// The Noto fonts are under the SIL Open Font License 1.1, which",
        "// permits embedding rasterized bitmaps. Platform-layer header:",
        "// it uses FreeInk types.",
        "//",
        "// MIT License (see: LICENSE)",
        "// Copyright (C) 2026 Tomaz Stih",
        "",
        "#pragma once",
        "",
        "#include <FreeInkUIFont.h>",
        "",
        "#include <cstdint>",
        "",
        "namespace inkerface::detail::fonts {",
        "",
        f"inline constexpr std::uint8_t {name}_bitmap[] = {{",
        *byte_lines(bitmap),
        "};",
        "",
        f"inline constexpr freeink::ui::FontGlyph {name}_glyphs[] = {{",
        *rows,
        "};",
        "",
        f"inline constexpr freeink::ui::BitmapFont {name} = {{",
        f"    {name}_bitmap, {name}_glyphs, 0x{first:04X}, 0x{last:04X},",
        f"    {line_height}, {ascent}, {widest}, {tallest}, {bpp}}};",
        "",
        "} // namespace inkerface::detail::fonts",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ttf", required=True, type=Path)
    parser.add_argument("--size", required=True, type=int, help="pixel size")
    parser.add_argument("--first", type=lambda v: int(v, 0), default=0x20)
    parser.add_argument("--last", type=lambda v: int(v, 0), default=0x7E)
    parser.add_argument("--alpha", action="store_true",
                        help="anti-aliased 4-bit glyphs (about 3x larger)")
    parser.add_argument("--format", choices=("ikf", "header", "builtin"),
                        default="ikf")
    parser.add_argument("--name", default="custom",
                        help="snake_case name for header/builtin output")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    if not 0 < args.size <= 200:
        sys.exit("error: --size must be 1..200")
    if not 0x20 <= args.first <= args.last or args.last - args.first + 1 > max_glyphs:
        sys.exit(f"error: range must start at 0x20 or later and hold at most "
                 f"{max_glyphs} characters")
    if not re.fullmatch(r"[a-z][a-z0-9_]*", args.name):
        sys.exit("error: --name must be lower snake_case")

    bitmap, glyphs, metrics = rasterize(args.ttf, args.size, args.first,
                                        args.last, args.alpha)
    source = f"{args.ttf.name} at {args.size} px, U+{args.first:04X}..U+{args.last:04X}"
    if args.format == "ikf":
        data = pack(args.first, args.last, bitmap, glyphs, metrics)
        args.out.write_bytes(data)
    elif args.format == "header":
        data = pack(args.first, args.last, bitmap, glyphs, metrics)
        args.out.write_text(header_text(args.name, data, source))
    else:
        data = bitmap
        args.out.write_text(builtin_text(args.name, args.first, args.last,
                                         bitmap, glyphs, metrics, source))
    print(f"wrote {args.out}: {len(glyphs)} glyphs, line height {metrics[0]}, "
          f"{len(data)} bytes")


if __name__ == "__main__":
    main()
